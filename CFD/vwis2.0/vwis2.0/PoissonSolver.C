    VecDuplicate(Aj, &G11);
    VecDuplicate(Aj, &G12);
    VecDuplicate(Aj, &G13);
    VecDuplicate(Aj, &G21);
    VecDuplicate(Aj, &G22);
    VecDuplicate(Aj, &G23);
    VecDuplicate(Aj, &G31);
